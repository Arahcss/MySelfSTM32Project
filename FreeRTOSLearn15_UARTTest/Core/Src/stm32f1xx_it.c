/**
  * @brief This function handles USART1 global interrupt.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */
	uint8_t ucRxData;					//存当前接收数据
	static uint8_t s_ucCount;		//存储计数	

	//判断中断是否有效
	if((USART1->SR & UART_FLAG_RXNE) != UART_FLAG_RXNE )
	{
		return;
	}
	
	//接收数据并清标志位
	ucRxData = USART1->DR;
	USART1->SR &= ~UART_FLAG_RXNE;
	
	//收到数据存入缓冲区
	aucUartRxBuffer[s_ucCount] = ucRxData;
	s_ucCount++;
	
	//接收结束后在末尾加\0表示字符串结束
	if(ucRxData == '\n')
	{
		aucUartRxBuffer[s_ucCount] = '\0';
		ucUartRxComplete = TRUE;
		s_ucCount = 0;
	}
	
	return ;
  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */

  /* USER CODE END USART1_IRQn 1 */
}

